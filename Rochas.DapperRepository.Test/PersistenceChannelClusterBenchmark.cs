    private static ThreadSnapshot CaptureThreads()
    {
        ThreadPool.GetAvailableThreads(out int availWorker, out int availIO);
        ThreadPool.GetMaxThreads(out int maxWorker, out int maxIO);
        ThreadPool.GetMinThreads(out int minWorker, out int minIO);
        return new ThreadSnapshot
        {
            ThreadPoolWorkerThreads = maxWorker,
            ThreadPoolCompletionPortThreads = maxIO,
            ActiveWorkerThreads = maxWorker - availWorker,
            ActiveCompletionPortThreads = maxIO - availIO,
            ThreadPoolPendingWorkItems = ThreadPool.PendingWorkItemCount
        };
    }

    private static PhaseMetric BuildPhaseMetric(string phaseName, List<long> times)
    {
        times.Sort();
        if (times.Count == 0) return new PhaseMetric { PhaseName = phaseName, TotalOps = 0 };
        return new PhaseMetric
        {
            PhaseName = phaseName, TotalOps = times.Count, TotalMs = times.Sum(),
            AvgMs = times.Average(), MinMs = times.Min(), MaxMs = times.Max(),
            P95Ms = times[Math.Min((int)(times.Count * 0.95), times.Count - 1)],
            P99Ms = times[Math.Min((int)(times.Count * 0.99), times.Count - 1)]
        };
    }

