            TestName = "Channel_SingleInvoice", Mode = "Channel", Invoices = 1, Nodes = 3,
            RecordsPerNode = 1, ElapsedMs = sw.ElapsedMilliseconds,
            Throughput = 1000.0 / Math.Max(sw.ElapsedMilliseconds, 1),
